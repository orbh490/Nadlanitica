-- סכמה ראשונית - מחליפה את ddl-auto=update. רצה כמו שהיא גם על PostgreSQL (פרודקשן) וגם על H2 במצב PostgreSQL (פיתוח וטסטים).
-- אורכי העמודות תואמים את הוולידציה ב-API (למשל לידים עד 300 תווים) - ברירת המחדל של Hibernate הייתה varchar(255),
-- ו-PostgreSQL זורק שגיאה על ערך ארוך יותר במקום לקצר אותו בשקט.
-- כל הטבלאות של משתמש מחוברות ל-app_user עם ON DELETE CASCADE, כדי שמחיקת חשבון תמחק את כל המידע שלו.

CREATE TABLE app_user (
    id             VARCHAR(36)                 NOT NULL PRIMARY KEY,
    email          VARCHAR(254)                NOT NULL,
    password_hash  VARCHAR(100)                NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    email_verified BOOLEAN                     NOT NULL,
    CONSTRAINT uk_app_user_email UNIQUE (email)
);

CREATE TABLE user_session (
    token      VARCHAR(64)                 NOT NULL PRIMARY KEY,
    user_id    VARCHAR(36)                 NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_user_session_user_id ON user_session (user_id);
CREATE INDEX ix_user_session_expires_at ON user_session (expires_at);

CREATE TABLE account_token (
    token      VARCHAR(64)                 NOT NULL PRIMARY KEY,
    user_id    VARCHAR(36)                 NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    purpose    VARCHAR(20)                 NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_account_token_user_id ON account_token (user_id);
CREATE INDEX ix_account_token_expires_at ON account_token (expires_at);

-- חישובים שמורים: נשמרים רק למשתמשים מחוברים, אבל העמודה nullable כי כך מוגדרת הישות
CREATE TABLE buyer_session (
    id               VARCHAR(36)                 NOT NULL PRIMARY KEY,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    user_id          VARCHAR(36)                 REFERENCES app_user (id) ON DELETE CASCADE,
    available_equity FLOAT(53)                   NOT NULL,
    monthly_income   FLOAT(53)                   NOT NULL,
    category         VARCHAR(20)                 NOT NULL CHECK (category IN ('SINGLE', 'REPLACEMENT', 'INVESTMENT')),
    market_value     FLOAT(53)                   NOT NULL,
    purchase_price   FLOAT(53)                   NOT NULL,
    subsidized       BOOLEAN                     NOT NULL,
    used_broker      BOOLEAN                     NOT NULL,
    term_years       INTEGER                     NOT NULL
);
CREATE INDEX ix_buyer_session_user_created ON buyer_session (user_id, created_at);

CREATE TABLE interest_area (
    id         VARCHAR(36)                 NOT NULL PRIMARY KEY,
    user_id    VARCHAR(36)                 NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    name       VARCHAR(60)                 NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_interest_area_user_name UNIQUE (user_id, name)
);

-- לידים מגיעים מטופס ציבורי בלי חשבון - לא קשורים ל-app_user
CREATE TABLE mortgage_lead (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    full_name  VARCHAR(300)                NOT NULL,
    phone      VARCHAR(300)                NOT NULL,
    email      VARCHAR(300),
    message    VARCHAR(300)
);
CREATE INDEX ix_mortgage_lead_created_at ON mortgage_lead (created_at);
